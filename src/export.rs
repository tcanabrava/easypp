//! `easypp export-cmake`: writes a CMakeLists.txt that builds the project the
//! way easypp does, so a course can move on to CMake with a project the
//! students already know. Every folder becomes the CMake target it always was.

use crate::builder;
use crate::project::{Library, Project, Target};
use crate::system::SysDep;
use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write;
use std::path::Path;

pub fn write(project: &Project, force: bool) -> Result<(), String> {
    if project.modules.has_header_units() {
        return Err(
            "CMake export does not support C++ header units. Build this project with easypp."
                .into(),
        );
    }
    let path = project.root.join("CMakeLists.txt");
    if path.exists() && !force {
        return Err("CMakeLists.txt already exists; use --force to replace it".into());
    }
    std::fs::write(&path, cmake(project)).map_err(|e| format!("cannot write CMakeLists.txt: {e}"))
}

/// What a system dependency is called in CMake.
fn cmake_dep(dep: &SysDep) -> String {
    match dep {
        SysDep::Pkg(name) if crate::kde::is_native(name) => name.clone(),
        SysDep::Pkg(name) if name.starts_with("Qt6") => format!("Qt6::{}", &name[3..]),
        SysDep::Pkg(name) => format!("PkgConfig::{}", pkg_var(name)),
        SysDep::Lib { name, .. } => name.clone(),
        SysDep::OpenMp => "OpenMP::OpenMP_CXX".into(),
        SysDep::CudaRuntime => "CUDA::cudart".into(),
    }
}

fn pkg_var(name: &str) -> String {
    name.chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() {
                c.to_ascii_uppercase()
            } else {
                '_'
            }
        })
        .collect()
}

fn list(items: impl IntoIterator<Item = String>) -> String {
    items.into_iter().collect::<Vec<_>>().join(" ")
}

fn path(p: &Path) -> String {
    p.to_string_lossy().into_owned()
}

fn cmake(project: &Project) -> String {
    let name = project.root.file_name().map_or("project".into(), |n| {
        n.to_string_lossy()
            .replace(|c: char| !c.is_ascii_alphanumeric(), "_")
    });
    let targets: Vec<&Target> = project.bins.iter().chain(&project.tests).collect();

    // Library target names: a library may share its name with a program
    // (examples/life has both), which CMake does not allow.
    let program_names: BTreeSet<&str> = targets.iter().map(|t| t.name.as_str()).collect();
    let lib_target: BTreeMap<&str, String> = project
        .libs
        .keys()
        .map(|n| {
            let target = if program_names.contains(n.as_str()) {
                format!("{n}_lib")
            } else {
                n.clone()
            };
            (n.as_str(), target)
        })
        .collect();

    let all_deps: BTreeSet<&SysDep> = project
        .libs
        .values()
        .flat_map(|l| l.system.iter())
        .chain(targets.iter().flat_map(|t| t.system.iter()))
        .collect();
    let mut qt: BTreeSet<String> = all_deps
        .iter()
        .filter_map(|d| match d {
            SysDep::Pkg(n) if n.starts_with("Qt6") => Some(n[3..].to_string()),
            _ => None,
        })
        .collect();
    if all_deps
        .iter()
        .any(|d| matches!(d, SysDep::Pkg(n) if crate::kde::is_native(n)))
    {
        qt.insert("Core".into());
    }
    let pkgs: Vec<&String> = all_deps
        .iter()
        .filter_map(|d| match d {
            SysDep::Pkg(n) if !n.starts_with("Qt6") && !crate::kde::is_native(n) => Some(n),
            _ => None,
        })
        .collect();
    let lib_dirs: BTreeSet<String> = all_deps
        .iter()
        .filter_map(|d| match d {
            SysDep::Lib { dir: Some(dir), .. } => Some(path(dir)),
            _ => None,
        })
        .collect();

    let mut out = String::new();
    let w = &mut out;
    let _ = writeln!(
        w,
        "# Generated by `easypp export-cmake` from the project's folders and #includes."
    );
    let _ = writeln!(
        w,
        "# Each folder in src/libs, src/bin and src/tests is the target it was in easypp.\n"
    );
    let standard_modules = project.modules.standard_sources().next().is_some();
    let version = if standard_modules {
        "4.5"
    } else if project.modules.is_empty() {
        "3.25"
    } else {
        "3.28"
    };
    let _ = writeln!(w, "cmake_minimum_required(VERSION {version})");
    let cuda = if project.has_cuda_sources() {
        " CUDA"
    } else {
        ""
    };
    if !cuda.is_empty()
        && let Some(code) = project
            .cuda
            .as_ref()
            .and_then(crate::cuda::Toolkit::architecture)
            .and_then(|arch| arch.strip_prefix("sm_"))
    {
        let _ = writeln!(
            w,
            "set(CMAKE_CUDA_ARCHITECTURES {code} CACHE STRING \"CUDA architectures\")"
        );
    }
    let _ = writeln!(w, "project({name} LANGUAGES C CXX{cuda})\n");
    if !cuda.is_empty() {
        let _ = writeln!(
            w,
            "set(CMAKE_CUDA_STANDARD {})\nset(CMAKE_CUDA_STANDARD_REQUIRED ON)\nset(CMAKE_CUDA_SEPARABLE_COMPILATION ON)",
            crate::cuda::STANDARD
        );
    }
    if project.cuda.is_some() {
        let _ = writeln!(w, "find_package(CUDAToolkit REQUIRED)\n");
    }
    if standard_modules {
        let _ = writeln!(
            w,
            r#"if(NOT CMAKE_GENERATOR MATCHES "^Ninja($| Multi-Config$)")
  message(FATAL_ERROR "Standard library modules require a Ninja generator.")
endif()
if(NOT EXISTS "${{CMAKE_CXX_STDLIB_MODULES_JSON}}")
  message(FATAL_ERROR "The selected C++ toolchain does not provide a standard library module manifest.")
endif()
"#
        );
    }
    let _ = writeln!(
        w,
        "set(CMAKE_CXX_STANDARD 23)\nset(CMAKE_CXX_STANDARD_REQUIRED ON)\nset(CMAKE_CXX_EXTENSIONS OFF)"
    );
    let _ = writeln!(
        w,
        "set(CMAKE_C_STANDARD 17)\nset(CMAKE_C_STANDARD_REQUIRED ON)\nset(CMAKE_C_EXTENSIONS OFF)"
    );
    let _ = writeln!(w, "set(CMAKE_EXPORT_COMPILE_COMMANDS ON)");
    let _ = writeln!(
        w,
        "if(NOT CMAKE_BUILD_TYPE)\n  set(CMAKE_BUILD_TYPE Debug)\nendif()\n"
    );
    let _ = writeln!(
        w,
        "# The project's own code: every warning is an error. Third-party code: no warnings."
    );
    if project.cuda.is_some() {
        let _ = writeln!(
            w,
            "set(EASYPP_WARNINGS \"$<$<COMPILE_LANGUAGE:CUDA>:{}>\" \"$<$<NOT:$<COMPILE_LANGUAGE:CUDA>>:{}>\")\n",
            crate::cuda::HOST_WARNINGS,
            crate::builder::WARNINGS.join(";")
        );
    } else {
        let _ = writeln!(
            w,
            "set(EASYPP_WARNINGS {})\n",
            crate::builder::WARNINGS.join(" ")
        );
    }
    let _ = writeln!(
        w,
        "# Debug builds: AddressSanitizer and UBSan, as in easypp."
    );
    let sanitize = "$<$<CONFIG:Debug>:-fsanitize=address,undefined;-fno-sanitize-recover=undefined;-fno-omit-frame-pointer>";
    let _ = writeln!(
        w,
        "add_compile_options(\"$<$<NOT:$<COMPILE_LANGUAGE:CUDA>>:{sanitize}>\")\nadd_link_options(\"$<HOST_LINK:{sanitize}>\")"
    );
    let _ = writeln!(
        w,
        "# Leak reports about GUI/system libraries that keep memory until exit are suppressed."
    );
    let _ = writeln!(
        w,
        "set(EASYPP_SANITIZER_DEFAULTS ${{CMAKE_BINARY_DIR}}/easypp_sanitizer_defaults.c)"
    );
    let _ = writeln!(
        w,
        "file(WRITE ${{EASYPP_SANITIZER_DEFAULTS}} [=[\n{}]=])\n",
        builder::SANITIZER_DEFAULTS
    );

    if !lib_dirs.is_empty() {
        let _ = writeln!(w, "link_directories({})\n", list(lib_dirs.into_iter()));
    }
    if !pkgs.is_empty() {
        if pkgs.iter().any(|name| crate::conan::provides(name))
            && let Some(dir) = crate::conan::package_dir()
            && let Ok(dir) = dir.strip_prefix(&project.root)
        {
            let _ = writeln!(
                w,
                "set(ENV{{PKG_CONFIG_PATH}} \"${{CMAKE_CURRENT_SOURCE_DIR}}/{}:$ENV{{PKG_CONFIG_PATH}}\")",
                dir.display()
            );
        }
        let _ = writeln!(w, "find_package(PkgConfig REQUIRED)");
        for pkg in &pkgs {
            let _ = writeln!(
                w,
                "pkg_check_modules({} REQUIRED IMPORTED_TARGET {pkg})",
                pkg_var(pkg)
            );
        }
        let _ = writeln!(w);
    }
    if all_deps.contains(&SysDep::OpenMp) {
        let _ = writeln!(w, "find_package(OpenMP REQUIRED)\n");
    }
    if !qt.is_empty() {
        let _ = writeln!(
            w,
            "find_package(Qt6 REQUIRED COMPONENTS {})",
            list(qt.iter().cloned())
        );
        let _ = writeln!(
            w,
            "set(CMAKE_AUTOMOC ON)\nset(CMAKE_AUTOUIC ON)\nset(CMAKE_AUTORCC ON)\n"
        );
    }

    let native: BTreeSet<String> = all_deps
        .iter()
        .filter_map(|d| match d {
            SysDep::Pkg(n) if crate::kde::is_native(n) => crate::kde::package_name(n),
            _ => None,
        })
        .collect();
    for package in native {
        let _ = writeln!(w, "find_package({package} REQUIRED)");
    }

    for name in &project.lib_order {
        library(w, project, project.libs.get(name).unwrap(), &lib_target);
    }

    if !project.tests.is_empty() {
        let _ = writeln!(w, "enable_testing()\n");
    }
    for target in &targets {
        program(w, project, target, &lib_target);
    }
    out
}

fn kconfig_sources(
    w: &mut String,
    files: &crate::qt::QtFiles,
    name: &str,
    sources: &mut Vec<String>,
) {
    if files.kconfig.is_empty() {
        return;
    }
    let var = format!("EASYPP_KCONFIG_{}", pkg_var(name));
    let _ = writeln!(w, "find_package(KF6Config REQUIRED)");
    let _ = writeln!(
        w,
        "kconfig_add_kcfg_files({var} {})",
        list(files.kconfig.iter().map(|p| path(p)))
    );
    sources.push(format!("${{{var}}}"));
}

fn module_sources(project: &Project, sources: &[std::path::PathBuf]) -> (Vec<String>, Vec<String>) {
    let (modules, ordinary): (Vec<_>, Vec<_>) = sources
        .iter()
        .partition(|src| project.modules.provides(src));
    (
        ordinary.into_iter().map(|src| path(src)).collect(),
        modules.into_iter().map(|src| path(src)).collect(),
    )
}

fn export_modules(w: &mut String, target: &str, visibility: &str, modules: Vec<String>) {
    if !modules.is_empty() {
        let _ = writeln!(
            w,
            "target_sources({target} {visibility} FILE_SET CXX_MODULES FILES {})",
            list(modules)
        );
    }
}

fn library(w: &mut String, project: &Project, lib: &Library, names: &BTreeMap<&str, String>) {
    let target = &names[lib.name.as_str()];
    let (mut sources, modules) = module_sources(project, &lib.sources);
    kconfig_sources(w, &lib.qt, target, &mut sources);
    // Listed so AUTOMOC/AUTOUIC see every Q_OBJECT header and .ui form.
    let moc_headers = lib
        .qt
        .moc
        .iter()
        .filter(|f| crate::project::Lang::of(f).is_none());
    sources.extend(moc_headers.chain(&lib.qt.ui).map(|s| path(s)));
    let deps: Vec<String> = lib
        .deps
        .iter()
        .map(|d| names[d.as_str()].clone())
        .chain(lib.system.iter().map(cmake_dep))
        .collect();
    let include_dir = if lib.third_party {
        let include = lib.dir.join("include");
        path(if include.is_dir() { &include } else { &lib.dir })
    } else {
        crate::project::LIBS_DIR.to_string()
    };

    let _ = writeln!(w, "# {}", path(&lib.dir));
    if sources.is_empty() && modules.is_empty() {
        let _ = writeln!(w, "add_library({target} INTERFACE)");
        let system = if lib.third_party { "SYSTEM " } else { "" };
        let _ = writeln!(
            w,
            "target_include_directories({target} {system}INTERFACE {include_dir})"
        );
        if !deps.is_empty() {
            let _ = writeln!(
                w,
                "target_link_libraries({target} INTERFACE {})",
                list(deps)
            );
        }
    } else {
        let _ = writeln!(w, "add_library({target} STATIC {})", list(sources));
        export_modules(w, target, "PUBLIC", modules);
        if target != &lib.name {
            let _ = writeln!(
                w,
                "set_target_properties({target} PROPERTIES OUTPUT_NAME {})",
                lib.name
            );
        }
        if lib.third_party {
            let _ = writeln!(
                w,
                "target_include_directories({target} SYSTEM PUBLIC {include_dir} ${{CMAKE_CURRENT_BINARY_DIR}})"
            );
            let _ = writeln!(w, "target_compile_options({target} PRIVATE -w)");
        } else {
            let _ = writeln!(
                w,
                "target_include_directories({target} PUBLIC {include_dir} ${{CMAKE_CURRENT_BINARY_DIR}})"
            );
            let _ = writeln!(
                w,
                "target_compile_options({target} PRIVATE ${{EASYPP_WARNINGS}})"
            );
        }
        if !deps.is_empty() {
            let _ = writeln!(w, "target_link_libraries({target} PUBLIC {})", list(deps));
        }
    }
    let _ = writeln!(w);
}

fn program(w: &mut String, project: &Project, target: &Target, names: &BTreeMap<&str, String>) {
    let (mut sources, modules) = module_sources(project, &target.sources);
    kconfig_sources(w, &target.qt, &target.name, &mut sources);
    let moc_headers = target
        .qt
        .moc
        .iter()
        .filter(|f| crate::project::Lang::of(f).is_none());
    sources.extend(
        moc_headers
            .chain(&target.qt.ui)
            .chain(&target.qt.qrc)
            .map(|s| path(s)),
    );
    // Resources of used libraries go straight into the program, as in easypp:
    // inside a static library their registration would be dropped.
    for lib in &target.libs {
        sources.extend(project.libs[lib].qt.qrc.iter().map(|s| path(s)));
    }
    let manifests = target.qt.gresource.iter().chain(
        target
            .libs
            .iter()
            .flat_map(|lib| &project.libs[lib].qt.gresource),
    );
    for (i, manifest) in manifests.enumerate() {
        let name = format!(
            "easypp_{}_gresource_{i}",
            target
                .name
                .replace(|c: char| !c.is_ascii_alphanumeric(), "_")
        );
        let output = format!("${{CMAKE_CURRENT_BINARY_DIR}}/{name}.c");
        let depfile = format!("${{CMAKE_CURRENT_BINARY_DIR}}/{name}.d");
        let input = format!("${{CMAKE_CURRENT_SOURCE_DIR}}/{}", path(manifest));
        let directory = format!(
            "${{CMAKE_CURRENT_SOURCE_DIR}}/{}",
            path(manifest.parent().unwrap())
        );
        let _ = writeln!(
            w,
            "find_program(EASYPP_GLIB_COMPILE_RESOURCES glib-compile-resources REQUIRED)"
        );
        let _ = writeln!(
            w,
            "add_custom_command(OUTPUT \"{output}\" COMMAND \"${{EASYPP_GLIB_COMPILE_RESOURCES}}\" --generate-source --c-name {name} --sourcedir \"{directory}\" --target \"{output}\" --dependency-file \"{depfile}\" \"{input}\" DEPENDS \"{input}\" DEPFILE \"{depfile}\" VERBATIM)"
        );
        let _ = writeln!(
            w,
            "set_source_files_properties(\"{output}\" PROPERTIES COMPILE_OPTIONS -Wno-overlength-strings)"
        );
        sources.push(format!("\"{output}\""));
    }
    let deps: Vec<String> = target
        .libs
        .iter()
        .map(|l| names[l.as_str()].clone())
        .chain(target.system.iter().map(cmake_dep))
        .collect();

    let name = &target.name;
    let _ = writeln!(w, "add_executable({name} {})", list(sources));
    if project.target_has_cuda_sources(target) {
        let _ = writeln!(
            w,
            "set_target_properties({name} PROPERTIES LINKER_LANGUAGE CXX CUDA_RUNTIME_LIBRARY Shared CUDA_RESOLVE_DEVICE_SYMBOLS ON)"
        );
    }
    if let Some(module) = target.qt.qml.as_ref().and_then(|qml| qml.module.as_ref()) {
        for dir in target.qt.qml_header_dirs() {
            let _ = writeln!(
                w,
                "target_include_directories({name} PRIVATE \"{}\")",
                dir.display()
            );
        }
        let _ = writeln!(
            w,
            "qt6_add_qml_module({name} URI {} VERSION 1.0 RESOURCE_PREFIX /qt/qml NO_PLUGIN NO_GENERATE_QMLDIR NO_CACHEGEN TYPEINFO {} OUTPUT_DIRECTORY \"${{CMAKE_CURRENT_BINARY_DIR}}/easypp-qml/{name}\")",
            module.uri,
            crate::qt::QML_TYPEINFO
        );
    }
    let qml = target.qt.qml.iter().chain(
        target
            .libs
            .iter()
            .filter_map(|lib| project.libs[lib].qt.qml.as_ref()),
    );
    for (index, resources) in qml.enumerate() {
        let _ = writeln!(
            w,
            "qt6_add_resources({name} easypp_qml_{index} PREFIX \"{}\" BASE \"{}\" FILES",
            resources.prefix,
            resources.base.display()
        );
        for file in &resources.files {
            let _ = writeln!(w, "    \"{}\"", file.display());
        }
        let _ = writeln!(w, ")");
    }
    export_modules(w, name, "PRIVATE", modules);
    let _ = writeln!(
        w,
        "target_include_directories({name} PRIVATE {} ${{CMAKE_CURRENT_BINARY_DIR}})",
        crate::project::LIBS_DIR
    );
    let _ = writeln!(
        w,
        "target_compile_options({name} PRIVATE ${{EASYPP_WARNINGS}})"
    );
    let _ = writeln!(
        w,
        "target_sources({name} PRIVATE $<$<CONFIG:Debug>:${{EASYPP_SANITIZER_DEFAULTS}}>)"
    );
    if !deps.is_empty() {
        let _ = writeln!(w, "target_link_libraries({name} PRIVATE {})", list(deps));
    }
    if target.kind == crate::project::Kind::Test {
        let _ = writeln!(
            w,
            "add_test(NAME {name} COMMAND {name} WORKING_DIRECTORY ${{CMAKE_SOURCE_DIR}})"
        );
        let _ = writeln!(w, "set_tests_properties({name} PROPERTIES TIMEOUT 60)");
    }
    let _ = writeln!(w);
}
